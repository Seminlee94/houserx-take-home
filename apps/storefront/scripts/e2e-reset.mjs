// Heavy, on-demand reset for the Playwright e2e stack.
//
// Drops and recreates a dedicated test database, reseeds it by running the
// backend migrations (which include the initial-data-seed migration script),
// reads the freshly generated publishable key out of the database, and writes
// e2e/.env.e2e for playwright.config.ts to consume.
//
// This is intentionally NOT part of `test:e2e`: the e2e tests never mutate the
// catalog, so the fixture only needs rebuilding when a dev explicitly wants a
// clean slate. Run it with `pnpm run e2e:reset`.
//
// Every knob is overridable by env var so this is not hard-wired to one machine.

import { execFileSync } from "node:child_process"
import { fileURLToPath } from "node:url"
import { writeFileSync } from "node:fs"
import path from "node:path"

const storefrontDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const backendDir = path.resolve(storefrontDir, "../backend")

const config = {
  container: process.env.E2E_PG_CONTAINER || "medusa-postgres",
  pgUser: process.env.E2E_PG_USER || "postgres",
  pgHost: process.env.E2E_PG_HOST || "localhost",
  pgPort: process.env.E2E_PG_PORT || "5432",
  testDb: process.env.E2E_DB_NAME || "medusa-dtc-starter-test",
  backendPort: process.env.E2E_BACKEND_PORT || "9001",
  storefrontPort: process.env.E2E_STOREFRONT_PORT || "8001",
}

const databaseUrl = `postgres://${config.pgUser}@${config.pgHost}:${config.pgPort}/${config.testDb}`
const backendUrl = `http://localhost:${config.backendPort}`
const storeCors = `http://localhost:${config.storefrontPort}`

// Run a psql command inside the Postgres container. We talk to the container
// directly rather than a host `psql` because this project's Postgres only runs
// in Docker (there is no host client on PATH).
function psql(db, sql) {
  return execFileSync(
    "docker",
    ["exec", config.container, "psql", "-U", config.pgUser, "-d", db, "-Atc", sql],
    { encoding: "utf8" }
  ).trim()
}

console.log(`[e2e-reset] dropping and recreating "${config.testDb}"`)
psql("postgres", `DROP DATABASE IF EXISTS "${config.testDb}" WITH (FORCE);`)
psql("postgres", `CREATE DATABASE "${config.testDb}";`)

console.log("[e2e-reset] running migrations + seed (this is the slow part)")
execFileSync("pnpm", ["medusa", "db:migrate"], {
  cwd: backendDir,
  stdio: "inherit",
  env: { ...process.env, DATABASE_URL: databaseUrl },
})

console.log("[e2e-reset] reading seeded publishable key")
const publishableKey = psql(
  config.testDb,
  "select token from api_key where title='Default Publishable API Key' and type='publishable' limit 1;"
)
if (!publishableKey.startsWith("pk_")) {
  throw new Error(`Expected a publishable key (pk_...), got: ${JSON.stringify(publishableKey)}`)
}

const envFile = path.join(storefrontDir, "e2e", ".env.e2e")
const contents = [
  "# Generated by scripts/e2e-reset.mjs. Do not edit or commit.",
  `E2E_DATABASE_URL=${databaseUrl}`,
  `E2E_BACKEND_URL=${backendUrl}`,
  `E2E_BACKEND_PORT=${config.backendPort}`,
  `E2E_STOREFRONT_PORT=${config.storefrontPort}`,
  `E2E_STORE_CORS=${storeCors}`,
  `E2E_PUBLISHABLE_KEY=${publishableKey}`,
  "",
].join("\n")
writeFileSync(envFile, contents)

console.log(`[e2e-reset] wrote ${path.relative(storefrontDir, envFile)}`)
console.log("[e2e-reset] done. Run `pnpm run test:e2e`.")
